export function getFighterById(id) {
  return GKO_FIGHTERS.find(f => f.id === id);
}

export function getFighterSheetPath(fighter) {
  const color = typeof fighter === 'string'
    ? (GKO_FIGHTERS.find(f => f.id === fighter)?.sheetColor || fighter)
    : fighter.sheetColor;
  return `${FIGHTER_BASE_PATH}/${color}.png`;
}

