function heroHash(heroId) {
  let hash = 0;
  const str = `bw-pref-${heroId}`;
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) - hash) + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

export function getHeroBestItems(hero) {
  const classPrefs = HERO_BEST_ITEMS[hero.classId];
  if (!classPrefs) return null;
  const base = classPrefs[hero.raceId];
  if (!base) return null;

  const h = heroHash(hero.id);
  return {
    weapon: base.weapon,
    ring: base.ring,
    relic: base.relic,
    happyLines: base.happyLines,
    wantLines: base.wantLines,
    personalSeed: h,
  };
}

export function checkBestItemEquipped(hero) {
  const prefs = getHeroBestItems(hero);
  if (!prefs) return { hasBest: false, bestSlots: [], totalBest: 0 };

  const equipment = hero.equipment || {};
  const bestSlots = [];

  if (equipment.weapon?.id === prefs.weapon) bestSlots.push('weapon');
  if (equipment.ring?.id === prefs.ring) bestSlots.push('ring');
  if (equipment.relic?.id === prefs.relic) bestSlots.push('relic');

  return { hasBest: bestSlots.length > 0, bestSlots, totalBest: bestSlots.length };
}

const ALL_BONUS_STATS = [
  'physicalDamage', 'magicDamage', 'defense', 'health', 'mana', 'stamina',
  'criticalChance', 'criticalDamage', 'evasion', 'block', 'attackSpeed',
  'accuracy', 'spellAccuracy', 'damageReduction', 'armorPenetration',
  'manaRegen', 'healthRegen', 'staminaRegen', 'drainHealth',
];

export function getBestItemBonuses(hero) {
  const { totalBest } = checkBestItemEquipped(hero);
  if (totalBest === 0) return {};

  const bonus = {};
  ALL_BONUS_STATS.forEach(attr => { bonus[attr] = totalBest; });
  return bonus;
}

export function checkInventoryForBestItems(hero, inventory) {
  const prefs = getHeroBestItems(hero);
  if (!prefs) return [];

  const equipment = hero.equipment || {};
  const found = [];

  const bestIds = [prefs.weapon, prefs.ring, prefs.relic];
  const equippedIds = Object.values(equipment).map(e => e?.id).filter(Boolean);

  for (const item of (inventory || [])) {
    if (bestIds.includes(item.id) && !equippedIds.includes(item.id)) {
      found.push(item);
    }
  }
  return found;
}
